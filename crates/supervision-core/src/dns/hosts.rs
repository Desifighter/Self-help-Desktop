use std::path::{Path, PathBuf};
use std::fs;
use std::io::{self, Write};
use tracing::{info, warn};

const BEGIN_TAG: &str = "# --- BEGIN SUPERVISION DESKTOP MANAGED BLOCKLIST ---";
const END_TAG: &str = "# --- END SUPERVISION DESKTOP MANAGED BLOCKLIST ---";

pub struct HostsManager {
    hosts_path: PathBuf,
}

impl HostsManager {
    pub fn new() -> Self {
        #[cfg(windows)]
        let hosts_path = PathBuf::from(r"C:\Windows\System32\drivers\etc\hosts");

        #[cfg(not(windows))]
        let hosts_path = PathBuf::from("/etc/hosts");

        Self { hosts_path }
    }

    pub fn with_custom_path(path: impl AsRef<Path>) -> Self {
        Self { hosts_path: path.as_ref().to_path_buf() }
    }

    pub fn apply_blocklist(&self, domains: &[String]) -> io::Result<()> {
        if !self.hosts_path.exists() {
            return Err(io::Error::new(io::ErrorKind::NotFound, "Hosts file not found"));
        }

        let content = fs::read_to_string(&self.hosts_path)?;
        let stripped = self.strip_managed_section(&content);

        let mut managed_block = String::new();
        managed_block.push_str(BEGIN_TAG);
        managed_block.push('\n');
        managed_block.push_str("# Automatically generated by Supervision Desktop. Do not edit this section.\n");

        for d in domains {
            let clean = d.trim().to_lowercase();
            if !clean.is_empty() {
                managed_block.push_str(&format!("0.0.0.0 {}\n", clean));
                if !clean.starts_with("www.") {
                    managed_block.push_str(&format!("0.0.0.0 www.{}\n", clean));
                }
            }
        }

        managed_block.push_str(END_TAG);
        managed_block.push('\n');

        let mut new_content = stripped.trim_end().to_string();
        if !new_content.is_empty() {
            new_content.push_str("\n\n");
        }
        new_content.push_str(&managed_block);

        // Atomic write via temp file
        let temp_path = self.hosts_path.with_extension("tmp");
        {
            let mut file = fs::File::create(&temp_path)?;
            file.write_all(new_content.as_bytes())?;
            file.sync_all()?;
        }

        fs::rename(&temp_path, &self.hosts_path)?;
        info!("Updated system hosts file with {} blocked domains", domains.len());
        Ok(())
    }

    pub fn remove_managed_blocklist(&self) -> io::Result<()> {
        if !self.hosts_path.exists() {
            return Ok(());
        }

        let content = fs::read_to_string(&self.hosts_path)?;
        let stripped = self.strip_managed_section(&content);

        let temp_path = self.hosts_path.with_extension("tmp");
        {
            let mut file = fs::File::create(&temp_path)?;
            file.write_all(stripped.as_bytes())?;
            file.sync_all()?;
        }

        fs::rename(&temp_path, &self.hosts_path)?;
        info!("Removed Supervision managed section from system hosts file");
        Ok(())
    }

    fn strip_managed_section(&self, content: &str) -> String {
        let mut result = String::new();
        let mut inside_section = false;

        for line in content.lines() {
            if line.contains(BEGIN_TAG) {
                inside_section = true;
                continue;
            }
            if line.contains(END_TAG) {
                inside_section = false;
                continue;
            }
            if !inside_section {
                result.push_str(line);
                result.push('\n');
            }
        }

        result
    }
}
